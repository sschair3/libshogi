    void initialize()
    {
        // 駒と持ち駒の価値
        Position::setValue({//  EMP   BFU   BKY   BKE   BGI   BKA   BHI   BKI
                            0, 90, 315, 405, 495, 855, 990, 540,
                            //  BOU   BTO   BNY   BNK   BNG   BUM   BRY
                            15000, 540, 540, 540, 540, 945, 1395, 0,
                            //        WFU   WKY   WKE   WGI   WKA   WHI   WKI
                            0, -90, -315, -405, -495, -855, -990, -540,
                            //  WOU   WTO   WNY   WNK   WNG   WUM   WRY
                            -15000, -540, -540, -540, -540, -945, -1395, 0});
        Position::handsValue({//  EMP    FU    KY    KE    GI    KA    HI    KI
                              {0, 0, 0, 0, 0, 0, 0, 0},
                              {0, 100, 350, 450, 550, 950, 1100, 600},
                              {0, 200, 700, 900, 1100, 1900, 2200, 1200},
                              {0, 300, 1050, 1350, 1650, 0, 0, 1800},
                              {0, 400, 1400, 1800, 2200, 0, 0, 2400},
                              {0, 500, 0, 0, 0, 0, 0, 0},
                              {0, 600, 0, 0, 0, 0, 0, 0},
                              {0, 700, 0, 0, 0, 0, 0, 0},
                              {0, 800, 0, 0, 0, 0, 0, 0},
                              {0, 900, 0, 0, 0, 0, 0, 0},
                              {0, 1000, 0, 0, 0, 0, 0, 0},
                              {0, 1100, 0, 0, 0, 0, 0, 0},
                              {0, 1200, 0, 0, 0, 0, 0, 0},
                              {0, 1300, 0, 0, 0, 0, 0, 0},
                              {0, 1400, 0, 0, 0, 0, 0, 0},
                              {0, 1500, 0, 0, 0, 0, 0, 0},
                              {0, 1600, 0, 0, 0, 0, 0, 0},
                              {0, 1700, 0, 0, 0, 0, 0, 0},
                              {0, 1800, 0, 0, 0, 0, 0, 0}});

        // 位置の点数表を、盤面の見た目の並びからマス番号の並びに直す
        for (int k = 0; k < 16; ++k)
        {
            for (int rank = 0; rank < 9; ++rank)
            {
                for (int col = 0; col < 9; ++col)
                {
                    // 列 col は 9筋から数えているので、筋 (0 = 1筋) は 8 - col
                    Square::Square sq = Square::fileAll[8 - col] | Square::rankAll[rank];
                    PST[k][sq] = LocationTable[k][rank * 9 + col];
                }
            }
        }
    }

    Eval locationEvaluation(const Position &p)
    {
        Eval value = 0;
        for (auto sq : Square::all)
        {
            Piece::Piece pc = p.square(sq);
            if (pc == Piece::EMP)
            {
                continue;
            }
            Piece::Piece kind = pc & Piece::Neutral; // 手番を外した駒の種類
            if (Piece::color(pc) == Color::Black)
            {
                value += PST[kind][sq];
            }
            else
            {
                // 後手の駒は盤を 180 度回して先手の表を引き、符号を反転する
                value -= PST[kind][80 - sq];
            }
        }
        return value;
    }

    Eval evaluate(Position &p)
    {
        return p.eval() + locationEvaluation(p);
    }

