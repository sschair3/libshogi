Eval rocateEvaluation(game::Position &p)
{
    Eval value = 0;
    for (size_t i = 0; i < 16; i++)
    {
        if (i == 0 || i == 15)
            continue;
        for (auto sq : Square::all)
        {
            Piece::Piece pc = p.square(sq);
            if (pc == Piece::EMP)
            {
                continue;
            }
            Piece::Piece kind = pc & Piece::Neutral;
            if (Piece::color(pc) == Color::Black)
            {
                value += PST[kind][sq];
            }
            else
            {
                value -= PST[kind][80 - sq];
            }
        }
    }
    return value;
};